import requests
import hashlib
from pathlib import Path

selected_files = ["s1.zip", "alignments.zip"]

file_map = {
    f["key"]: f for f in metadata["files"]
}

for filename in selected_files:

    if filename not in file_map:
        raise FileNotFoundError(filename + " not found!")

    info = file_map[filename]

    download_url = info["links"]["download"]

    destination = GRID_DOWNLOADS / filename

    print("\nDownloading:", filename)
    print("Size:", round(info["size"] / (1024**2), 2), "MB")

    if destination.exists() and destination.stat().st_size == info["size"]:
        print("Already downloaded. Skipping.")
        continue

    md5 = hashlib.md5()
    downloaded = 0

    with requests.get(
        download_url,
        stream=True,
        timeout=(30, 300)
    ) as r:

        r.raise_for_status()

        with open(destination, "wb") as f:

            for chunk in r.iter_content(chunk_size=1024*1024):

                if chunk:
                    f.write(chunk)
                    md5.update(chunk)
                    downloaded += len(chunk)

                    print(
                        f"\rDownloaded: {downloaded / (1024**2):.1f} MB",
                        end=""
                    )

    expected_md5 = info["checksum"].replace("md5:", "")

    if md5.hexdigest() != expected_md5:
        raise ValueError("Checksum mismatch: " + filename)

    print("\nDownload and checksum verified:", filename)

print("\nALL DATASETS DOWNLOADED SUCCESSFULLY!")